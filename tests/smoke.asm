;------------------------------------------------------------
; ツールチェーン疎通用スモークテスト
;   The Macroassembler AS (asl) でアセンブルする最小プログラム。
;   1 + 2 を計算し、結果をポート 10h へ出力して HALT する。
;   tests/smoke_emu.py が出力値 03h を検証する。
;------------------------------------------------------------
	cpu	z80
	org	0100h

start:	ld	a,1
	ld	b,2
	add	a,b		; A = 3
	out	(10h),a		; ポート10hへ結果を出力
	halt

	end
