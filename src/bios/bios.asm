;==============================================================
; PC-8001 CP/M 2.2 BIOS 雛形
; doc/設計/03_BIOS構成.md 準拠
;   - BIOS_ORG = 0E900h
;   - ジャンプテーブル: 17エントリ × 3バイト = 51バイト
;   - コンソール入出力: VRAM 0F300h への直接書き込み
;
; ビルド:
;   asl -D origin=0E900h -o build/bios.p src/bios/bios.asm
;   p2bin build/bios.p build/bios.bin
;==============================================================
	cpu	z80

	ifndef	origin
origin	equ	0E900h
	endif

	org	origin

;--------------------------------------------------------------
; ジャンプテーブル (各エントリ JP nn = 3バイト)
; vec(n) = origin + 3*n
;--------------------------------------------------------------
	JP	BOOT		; 0: BOOT   コールドブート
	JP	WBOOT		; 1: WBOOT  ウォームブート
	JP	CONST		; 2: CONST  コンソール入力状態
	JP	CONIN		; 3: CONIN  コンソール1文字入力
	JP	CONOUT		; 4: CONOUT コンソール1文字出力
	JP	LIST		; 5: LIST   プリンタ出力(ダミー)
	JP	PUNCH		; 6: PUNCH  パンチ出力(ダミー)
	JP	READER		; 7: READER リーダ入力(ダミー)
	JP	HOME		; 8: HOME   トラック0シーク
	JP	SELDSK		; 9: SELDSK ディスク選択
	JP	SETTRK		; 10: SETTRK トラック設定
	JP	SETSEC		; 11: SETSEC セクタ設定
	JP	SETDMA		; 12: SETDMA DMAアドレス設定
	JP	READ		; 13: READ   セクタ読込
	JP	WRITE		; 14: WRITE  セクタ書込
	JP	LISTST		; 15: LISTST プリンタ状態
	JP	SECTRAN		; 16: SECTRAN 論理→物理セクタ変換

;--------------------------------------------------------------
; BOOT: コールドブート
;   スタックポインタ設定→サインオン文字列出力→HALT
;   TODO: 実機ではCCPへ #35/#37
;--------------------------------------------------------------
BOOT:
	LD	SP, 0DF00h	; スタックポインタ設定

	; サインオン文字列を CONOUT ループで出力
	LD	HL, SIGNON	; HL = 文字列先頭
BOOT_LOOP:
	LD	A, (HL)		; 1文字取得
	OR	A		; NUL(0)なら終了
	JR	Z, BOOT_DONE
	LD	C, A		; CONOUT: C = 文字
	CALL	CONOUT
	INC	HL
	JR	BOOT_LOOP
BOOT_DONE:
	HALT			; TODO: 実機ではCCPへ #35/#37

;--------------------------------------------------------------
; WBOOT: ウォームブート
;   TODO: CCP/BDOS再ロード #10/#35
;--------------------------------------------------------------
WBOOT:
	HALT			; TODO: CCP/BDOS再ロード #10/#35

;--------------------------------------------------------------
; CONST: コンソール入力状態確認
;   戻り: A=0FFh(有り) / A=00h(無し)(CP/M規約)
;   雛形は常に「無し」(00h)を返す(実装は #32)
;--------------------------------------------------------------
CONST:
	XOR	A		; A = 0(入力なし)
	RET

;--------------------------------------------------------------
; CONIN: コンソール1文字入力
;   戻り: A = 入力文字
;   本来は入力があるまでブロッキングする(実装は #32)
;   雛形は即 EOF(1Ah)を返すダミー
;--------------------------------------------------------------
CONIN:
	LD	A, 1Ah		; EOF代替文字
	RET

;--------------------------------------------------------------
; CONOUT: コンソール1文字出力
;   入力: C = 出力文字
;   動作: VRAM(0F300h + CURPOS)へ書き込み、CURPOSを+1
;   制御文字の処理は #32 で実装
;--------------------------------------------------------------
CONOUT:
	PUSH	AF
	PUSH	HL
	PUSH	DE

	LD	HL, (CURPOS)	; カーソル位置(0F300hからのオフセット)取得
	LD	DE, 0F300h	; VRAMベースアドレス
	ADD	HL, DE		; VRAM書き込みアドレス = 0F300h + CURPOS
	LD	(HL), C		; 文字を書き込む

	; カーソル位置を +1 更新
	LD	HL, (CURPOS)
	INC	HL
	LD	(CURPOS), HL

	POP	DE
	POP	HL
	POP	AF
	RET

;--------------------------------------------------------------
; LIST: プリンタ出力 (未使用ダミー)
;--------------------------------------------------------------
LIST:
	RET

;--------------------------------------------------------------
; PUNCH: パンチ出力 (未使用ダミー)
;--------------------------------------------------------------
PUNCH:
	RET

;--------------------------------------------------------------
; READER: リーダ入力 (未使用ダミー)
;   戻り: A=0x1A(EOF)
;--------------------------------------------------------------
READER:
	LD	A, 1Ah
	RET

;--------------------------------------------------------------
; HOME: トラック0シーク (雛形ではダミー)
;--------------------------------------------------------------
HOME:
	RET

;--------------------------------------------------------------
; SELDSK: ディスク選択
;   入力: C = ドライブ番号
;   戻り: HL = DPHアドレス(HL=0:無効) ← 雛形では常に無効
;--------------------------------------------------------------
SELDSK:
	LD	HL, 0		; HL = 0(無効)
	RET

;--------------------------------------------------------------
; SETTRK: トラック設定 (雛形ではダミー)
;   入力: BC = トラック番号
;--------------------------------------------------------------
SETTRK:
	RET

;--------------------------------------------------------------
; SETSEC: セクタ設定 (雛形ではダミー)
;   入力: BC = セクタ番号
;--------------------------------------------------------------
SETSEC:
	RET

;--------------------------------------------------------------
; SETDMA: DMAアドレス設定 (雛形ではダミー)
;   入力: BC = DMAアドレス
;--------------------------------------------------------------
SETDMA:
	RET

;--------------------------------------------------------------
; READ: セクタ読込 (雛形では常にエラー)
;   戻り: A=1(エラー)
;--------------------------------------------------------------
READ:
	LD	A, 1		; エラー
	RET

;--------------------------------------------------------------
; WRITE: セクタ書込 (雛形では常にエラー)
;   入力: C = 書込タイプ
;   戻り: A=1(エラー)
;--------------------------------------------------------------
WRITE:
	LD	A, 1		; エラー
	RET

;--------------------------------------------------------------
; LISTST: プリンタ状態確認
;   戻り: A=0xFF(常時出力可)
;--------------------------------------------------------------
LISTST:
	LD	A, 0FFh		; 常時出力可
	RET

;--------------------------------------------------------------
; SECTRAN: 論理→物理セクタ変換
;   入力: BC = 論理セクタ番号, DE = 変換テーブルアドレス
;   戻り: HL = 物理セクタ番号
;   雛形では DE(変換表)は未使用、常に恒等変換(HL = BC)
;--------------------------------------------------------------
SECTRAN:
	LD	H, B		; HL = BC (恒等変換)
	LD	L, C
	RET

;--------------------------------------------------------------
; データ領域
;--------------------------------------------------------------
SIGNON:
	DB	'PC-8001 CP/M 2.2 BIOS', 0	; サインオン文字列(NUL終端)

CURPOS:
	DW	0				; VRAMカーソル位置(0F300hからのオフセット)

	end
